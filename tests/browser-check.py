"""Browser smoke checks against the running sample workspace (Chrome required)."""
from playwright.sync_api import sync_playwright, expect
from pathlib import Path
import json

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/google-chrome', headless=True, args=['--no-sandbox'])
    page = browser.new_page(viewport={'width': 1440, 'height': 1050})
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto('http://localhost:4200/', wait_until='networkidle')
    expect(page.get_by_role('heading', name='Workspace overview')).to_be_visible()
    page.get_by_role('button', name='New project', exact=True).last.click()
    dialog = page.get_by_role('dialog', name='New project')
    dialog.get_by_label('Name', exact=True).fill('Browser verification project')
    dialog.get_by_label('Description').fill('Temporary project created by automated verification.')
    dialog.get_by_label('Start date').fill('2026-10-12')
    dialog.get_by_label('Due date').fill('2026-11-12')
    dialog.get_by_role('button', name='Save changes').click()
    expect(dialog).not_to_be_visible()
    page.get_by_role('link', name='Browser verification project', exact=True).first.click()
    expect(page.get_by_role('heading', name='Browser verification project', exact=True)).to_be_visible()
    page.get_by_role('button', name='New task', exact=True).click()
    dialog = page.get_by_role('dialog', name='New task')
    dialog.get_by_label('Task title').fill('Browser verified task')
    dialog.get_by_label('Assignee').select_option(label='Alex Morgan')
    dialog.get_by_label('Start date').fill('2026-10-12')
    dialog.get_by_label('Due date').fill('2026-10-20')
    dialog.get_by_label('Estimated hours').fill('6')
    dialog.get_by_role('button', name='Save changes').click()
    expect(dialog).not_to_be_visible()
    page.get_by_label('Status for Browser verified task').select_option('in-progress')
    expect(page.locator('.lane-in-progress').get_by_role('heading', name='Browser verified task')).to_be_visible()
    page.reload(wait_until='networkidle')
    expect(page.locator('.lane-in-progress').get_by_role('heading', name='Browser verified task')).to_be_visible()
    # Real drag-and-drop, plus accessible status selector checked above.
    page.locator('.task-card').filter(has_text='Browser verified task').drag_to(page.locator('.lane-review'))
    expect(page.locator('.lane-review').get_by_role('heading', name='Browser verified task')).to_be_visible()
    page.get_by_role('button', name='Timeline', exact=True).click()
    expect(page.locator('.gantt-bar').filter(has_text='Browser verified task')).to_be_visible()
    page.get_by_role('button', name='Open Browser verified task', exact=True).click()
    detail = page.get_by_role('dialog', name='Task details')
    detail.get_by_label('Comment', exact=True).fill('@Alex Morgan Browser comment verified.')
    detail.get_by_role('button', name='Post comment').click()
    expect(detail.locator('.comment p').filter(has_text='@Alex Morgan Browser comment verified.')).to_be_visible()
    detail.get_by_role('button', name='Log time').click()
    time_dialog = page.get_by_role('dialog', name='New time entry')
    time_dialog.get_by_label('Hours', exact=True).fill('1.5')
    time_dialog.get_by_role('button', name='Save changes').click()
    expect(time_dialog).not_to_be_visible()
    expect(detail.get_by_text('1.50h', exact=True)).to_be_visible()
    detail.get_by_role('button', name='Start timer').click()
    expect(detail.get_by_role('button', name='Stop ·', exact=False)).to_be_visible()
    detail.get_by_role('button', name='Stop ·', exact=False).click()
    expect(detail.get_by_role('button', name='Start timer')).to_be_visible()
    detail.get_by_label('Upload file').set_input_files({'name': 'browser-check.txt', 'mimeType': 'text/plain', 'buffer': b'Browser upload verified'})
    expect(detail.get_by_text('browser-check.txt', exact=True)).to_be_visible()
    with page.expect_download() as download:
        detail.get_by_label('Download browser-check.txt').click()
    assert Path(download.value.path()).read_bytes() == b'Browser upload verified'
    detail.get_by_role('button', name='Close dialog').click()
    page.get_by_role('button', name='Milestones', exact=True).click()
    page.get_by_role('button', name='New milestone').click()
    dialog = page.get_by_role('dialog', name='New milestone')
    dialog.get_by_label('Name', exact=True).fill('Verification complete')
    dialog.get_by_label('Due date').fill('2026-10-20')
    dialog.get_by_role('button', name='Save changes').click()
    expect(dialog).not_to_be_visible()
    page.get_by_label('Complete Verification complete').click()
    expect(page.get_by_label('Complete Verification complete')).to_be_checked()
    page.get_by_role('button', name='Reports', exact=True).click()
    with page.expect_download() as download:
        page.get_by_role('button', name='Export CSV').click()
    assert 'Browser verified task' in Path(download.value.path()).read_text()
    # Clean up only the test-generated project and related data.
    page.on('dialog', lambda d: d.accept())
    page.get_by_role('button', name='Delete project', exact=True).click()
    expect(page.get_by_role('heading', name='Your projects')).to_be_visible()
    page.goto('http://localhost:4200/', wait_until='networkidle')
    page.screenshot(path='/home/user/meridian-preview.png', full_page=True)
    page.get_by_role('link', name='Website relaunch', exact=True).first.click()
    expect(page.get_by_role('heading', name='Website relaunch', exact=True)).to_be_visible()
    page.screenshot(path='/home/user/meridian-board.png', full_page=True)
    mobile = browser.new_page(viewport={'width': 390, 'height': 844})
    mobile.goto('http://localhost:4200/', wait_until='networkidle')
    expect(mobile.get_by_role('heading', name='Workspace overview')).to_be_visible()
    mobile.get_by_label('Toggle navigation').click()
    expect(mobile.get_by_role('link', name='Team', exact=True)).to_be_visible()
    mobile.screenshot(path='/home/user/meridian-mobile.png', full_page=True)
    assert not errors, errors
    print(json.dumps({'result': 'PASS', 'checks': ['project/task creation', 'assignment', 'status selector', 'drag-and-drop', 'reload persistence', 'Gantt timeline', 'comment/mention', 'manual time', 'timer start/stop', 'file upload/download', 'milestone completion', 'CSV export', 'cascade deletion', 'mobile navigation'], 'browser_errors': errors}, indent=2))
    browser.close()